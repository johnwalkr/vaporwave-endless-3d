// MetalShaders generates ios/App/Shaders.metal from the OpenGL shaders, so
// the iPhone renders exactly like the desktop GPU renderer. The sky/floor
// shader is translated mechanically; the small passes are written below.
//
// Coordinates: Metal textures and fragment positions have row 0 at the top,
// like the CPU renderer and the way the GL renderer stores its images, so
// the per-pixel code is unchanged. Only the geometry vertex shader (NDC y
// points up) and depth (0..1 instead of -1..1) differ, and the final blit
// needs no flip.
func MetalShaders() string {
	var b strings.Builder
	b.WriteString("// Generated by MetalShaders() in metalparams.go from the OpenGL shaders in gl.go.\n")
	b.WriteString("// Do not edit. Regenerate: UPDATE_SHADERS=1 go test -run TestMetalShaders .\n")
	b.WriteString("#include <metal_stdlib>\nusing namespace metal;\n\n")
	fmt.Fprintf(&b, "#define NPARAMS %d\n", nParams)
	b.WriteString("#define PU constant float4* U, uint4 UI\n#define AU U, UI\n")
	for _, d := range bgDefs {
		fmt.Fprintf(&b, "#define %s U[%d].%s\n", d.n, d.i, d.s)
	}
	fmt.Fprintf(&b, "#define RINGS %d\n#define RAMP %d\n#define BODY %d\n#define NEB %d\n#define FARD %d.0\n", pRings, pRAmp, pBody, pNeb, farDist)
	b.WriteString(glslToMetal(glslHash))
	body := bgBody[:strings.Index(bgBody, "void main(){")]
	b.WriteString(glslToMetal(body))
	b.WriteString(metalPasses)
	return b.String()
}

var (
	reVec  = regexp.MustCompile(`\bvec([234])\b`)
	reIVec = regexp.MustCompile(`\bivec([234])\b`)
	reUVec = regexp.MustCompile(`\buvec([234])\b`)
	reSky  = regexp.MustCompile(`([^A-Za-z0-9_])sky\(`)
)

func glslToMetal(s string) string {
	s = reVec.ReplaceAllString(s, "float$1")
	s = reIVec.ReplaceAllString(s, "int$1")
	s = reUVec.ReplaceAllString(s, "uint$1")
	// helpers that read the parameter block get it as extra arguments
	for _, sig := range []string{"float3 spaceSky(float3 c, float3 d)", "float3 sky(float3 d)",
		"float3 spaceFloor(float hx,float hz,float fpz)", "float3 floorC(float3 d)"} {
		s = strings.Replace(s, sig+"{", "static "+sig[:len(sig)-1]+", PU){", 1)
	}
	for _, f := range []string{"uint hashu(", "float sat(", "float gridCov("} {
		s = strings.Replace(s, "\n"+f, "\nstatic "+f, 1)
	}
	s = strings.ReplaceAll(s, "spaceSky(c,d)", "spaceSky(c,d,AU)")
	s = strings.ReplaceAll(s, "spaceFloor(hx,hz,fpz)", "spaceFloor(hx,hz,fpz,AU)")
	// add AU to every call of sky(...)
	var out strings.Builder
	for {
		loc := reSky.FindStringIndex(s)
		if loc == nil {
			out.WriteString(s)
			break
		}
		open := loc[1]
		depth, k := 1, open
		for depth > 0 {
			switch s[k] {
			case '(':
				depth++
			case ')':
				depth--
			}
			k++
		}
		out.WriteString(s[:k-1])
		if !strings.HasSuffix(s[:k-1], "PU") {
			out.WriteString(",AU")
		}
		out.WriteString(")")
		s = s[k:]
	}
	return out.String()
}

const metalPasses = `
// ---- full-screen triangle ----------------------------------------------------
struct FSOut { float4 pos [[position]]; };

vertex FSOut fsVS(uint vid [[vertex_id]]) {
	float2 q = float2(float((vid << 1) & 2), float(vid & 2));
	FSOut o; o.pos = float4(q * 2.0 - 1.0, 0.0, 1.0); return o;
}

// ---- 1. sky + floor -------------------------------------------------------------
fragment float4 bgFS(FSOut in [[stage_in]], constant float4* U [[buffer(0)]], constant uint4& UI [[buffer(1)]]) {
	float px = in.pos.x - 0.5, py = in.pos.y - 0.5;
	float a = (px - CX) * INVF, b = (CY - py) * INVF;
	float3 d = CAMF + CAMU * b + CAMR * a;
	float3 c;
	if (d.y >= 0.0 || FULLSKY) c = sky(normalize(d), AU); else c = floorC(d, AU);
	return float4(c, 1.0);
}

// ---- 2. geometry (anti-aliased by the CPU-computed edge distances) ------------
struct GeoIn {
	float3 pos [[attribute(0)]];
	float4 col [[attribute(1)]];
	float2 dh  [[attribute(2)]];
};
struct GeoOut { float4 pos [[position]]; float4 col; float2 dh; };

vertex GeoOut geoVS(GeoIn v [[stage_in]], constant float2& vp [[buffer(1)]]) {
	GeoOut o;
	o.pos = float4((v.pos.x + 0.5) / vp.x * 2.0 - 1.0, 1.0 - (v.pos.y + 0.5) / vp.y * 2.0, 1.0 - min(v.pos.z * 0.3, 1.0), 1.0);
	o.col = v.col; o.dh = v.dh;
	return o;
}

fragment float4 geoFS(GeoOut in [[stage_in]]) {
	float cov = clamp(in.dh.y + 0.5 - abs(in.dh.x), 0.0, 1.0);
	return float4(in.col.rgb * cov, in.col.a * cov);
}

// ---- 3. bloom: bright-pass 4x4 downsample, then separable box blurs ----------
fragment float4 downFS(FSOut in [[stage_in]], texture2d<float> src [[texture(0)]]) {
	int2 b = int2(in.pos.xy);
	int2 sz = int2(src.get_width(), src.get_height());
	float3 s = float3(0.0); int n = 0;
	for (int y = 0; y < 4; y++) for (int x = 0; x < 4; x++) {
		int2 q = b * 4 + int2(x, y);
		if (q.x < sz.x && q.y < sz.y) { s += max(src.read(uint2(q)).rgb - 0.62, float3(0.0)); n++; }
	}
	return float4(s / float(max(n, 1)), 1.0);
}

fragment float4 blurFS(FSOut in [[stage_in]], texture2d<float> src [[texture(0)]], constant int2& dirRad [[buffer(0)]]) {
	int2 q = int2(in.pos.xy);
	int2 sz = int2(src.get_width(), src.get_height());
	int2 dd = dirRad.x == 0 ? int2(1, 0) : int2(0, 1);
	int r = dirRad.y;
	float3 s = float3(0.0);
	for (int k = -r; k <= r; k++) s += src.read(uint2(clamp(q + dd * k, int2(0), sz - 1))).rgb;
	return float4(s / float(2 * r + 1), 1.0);
}

// ---- 4. composite: bloom, VHS effects, tone curve -----------------------------
struct CompP { float4 P[3]; uint4 F; };

static float tone(float x) {
	if (x <= 0.0) return 0.0;
	if (x > 0.75) x = 0.75 + 0.25 * (1.0 - 1.0 / (1.0 + (x - 0.75) * 4.0));
	return min(x, 1.0);
}

fragment float4 compFS(FSOut in [[stage_in]], texture2d<float> scene [[texture(0)]], texture2d<float> bloomT [[texture(1)]],
                       constant CompP& cp [[buffer(0)]]) {
	constexpr sampler lin(filter::linear, address::clamp_to_edge);
	int W = int(cp.P[1].x), H = int(cp.P[1].y);
	int x = int(in.pos.x), y = int(in.pos.y);
	uint frame = cp.F.x;
	float glitch = cp.P[0].y;
	int off = 0;
	if (glitch > 0.0) {
		uint band = hashu(uint(y / (6 + int(frame % 5u) * 3)), frame / 2u, 5u);
		if (float(band & 1023u) / 1023.0 < glitch * 0.8)
			off = int((float((band >> 10u) & 1023u) / 1023.0 - 0.5) * glitch * float(W) * 0.35);
	}
	int ca = int(cp.P[2].z) + int(glitch * 6.0);
	float sl = 1.0;
	if (y % 3 == 2) sl = 1.0 - 0.16 * cp.P[2].x;
	float tb = float((int(frame) * 2 + H - y) % (H * 2)) / float(H);
	if (tb < 0.06) sl *= 1.0 + 0.08 * cp.P[2].w;
	int sx = x + off;
	if (sx < 0) sx += W; else if (sx >= W) sx -= W;
	int xr = max(sx - ca, 0), xb = min(sx + ca, W - 1);
	float3 c = float3(scene.read(uint2(xr, y)).r, scene.read(uint2(sx, y)).g, scene.read(uint2(xb, y)).b);
	float2 buv = float2((float(sx) + 0.5) * 0.25, (float(y) + 0.5) * 0.25) / float2(bloomT.get_width(), bloomT.get_height());
	c += bloomT.sample(lin, buv).rgb * cp.P[0].x;
	float vx = float(x) / float(W) - 0.5, vy = float(y) / float(H) - 0.5;
	float v = (1.0 - 0.55 * (vx * vx + vy * vy)) * sl;
	uint rs = hashu(uint(x), uint(y), frame * 7u + 99u);
	float gr = (float(rs >> 24u) / 255.0 - 0.5) * (0.035 * cp.P[2].y + glitch * 0.25) + cp.P[0].z;
	c = c * v + gr;
	return float4(tone(c.r), tone(c.g), tone(c.b), 1.0);
}

// ---- 5. scale to the screen -----------------------------------------------------
fragment float4 blitFS(FSOut in [[stage_in]], texture2d<float> src [[texture(0)]], constant float4& P [[buffer(0)]]) {
	constexpr sampler lin(filter::linear, address::clamp_to_edge);
	return float4(src.sample(lin, in.pos.xy / P.xy).rgb, 1.0);
}
`
